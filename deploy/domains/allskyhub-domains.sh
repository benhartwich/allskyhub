#!/bin/bash
# Own domains for public pages (roadmap #17), run as root by allskyhub-domains.timer.
#
# The hub (unprivileged) leaves requests in /var/lib/allskyhub-server/domains/:
#   <domain>.request  set the domain up: certificate (certbot standalone, nginx stopped
#                     for a few seconds) and an nginx server that passes it to the hub
#   <domain>.remove   take it down again
# and reads the answers <domain>.ok / <domain>.failed / <domain>.removed.
# Everything from that folder is untrusted: names are checked again here, never put into
# a shell unquoted, and a domain must resolve to this server before certbot runs.
set -euo pipefail

SPOOL=/var/lib/allskyhub-server/domains
HUB_HOST=${ALLSKYHUB_HUB_HOST:-allskyhub.org}
SITES=/etc/nginx/sites-available
ENABLED=/etc/nginx/sites-enabled
DOMAIN_RE='^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$'

answer() {  # answer <domain> <ok|failed|removed> [message]
    local file="$SPOOL/$1.$2"
    printf '%s\n' "${3:-}" > "$file"
    chown allskyhub-server:allskyhub-server "$file"
    rm -f -- "$SPOOL/$1.request" "$SPOOL/$1.remove"
}

addresses() { getent ahosts "$1" | awk '{print $1}' | sort -u; }

valid() {
    local d=$1
    [[ ${#d} -le 253 && $d =~ $DOMAIN_RE && $d != "$HUB_HOST" && $d != *".$HUB_HOST" ]]
}

points_here() {
    local theirs mine
    theirs=$(addresses "$1") || return 1
    mine=$(addresses "$HUB_HOST")
    [[ -n $theirs ]] || return 1
    while read -r ip; do
        grep -qxF -- "$ip" <<<"$mine" || return 1
    done <<<"$theirs"
}

write_site() {
    local d=$1 conf="$SITES/allskyhub-domain-$1.conf"
    cat > "$conf" <<NGINX
# Generated by allskyhub-domains.sh for an own domain of a public sky page (roadmap #17).
server {
    listen 80;
    listen [::]:80;
    server_name $d;
    access_log /var/log/nginx/allskyhub/access.log allskyhub_noquery;
    location / { return 301 https://$d\$request_uri; }
}
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name $d;
    ssl_certificate     /etc/letsencrypt/live/$d/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$d/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    add_header Strict-Transport-Security "max-age=31536000" always;
    access_log /var/log/nginx/allskyhub/access.log allskyhub_noquery;
    client_max_body_size 1m;
    location / {
        proxy_pass http://allskyhub_server;
        proxy_http_version 1.1;
        proxy_set_header Connection "";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;
    }
}
NGINX
    ln -sf "$conf" "$ENABLED/allskyhub-domain-$d.conf"
}

setup() {
    local d=$1
    if ! valid "$d"; then answer "$d" failed "Ungültiger Name."; return; fi
    if ! points_here "$d"; then
        answer "$d" failed "Die Domain zeigt nicht auf $HUB_HOST (DNS prüfen)."; return
    fi
    if ! certbot certonly --standalone --non-interactive --agree-tos --keep-until-expiring \
            --cert-name "$d" -d "$d" \
            --pre-hook "systemctl stop nginx" --post-hook "systemctl start nginx" \
            >>/var/log/allskyhub-domains.log 2>&1; then
        answer "$d" failed "Let's Encrypt hat kein Zertifikat ausgestellt."; return
    fi
    write_site "$d"
    if nginx -t >>/var/log/allskyhub-domains.log 2>&1; then
        systemctl reload nginx
        answer "$d" ok
    else
        rm -f -- "$ENABLED/allskyhub-domain-$d.conf" "$SITES/allskyhub-domain-$d.conf"
        answer "$d" failed "Die nginx-Konfiguration ließ sich nicht laden."
    fi
}

teardown() {
    local d=$1
    if ! valid "$d"; then answer "$d" removed; return; fi
    rm -f -- "$ENABLED/allskyhub-domain-$d.conf" "$SITES/allskyhub-domain-$d.conf"
    nginx -t >/dev/null 2>&1 && systemctl reload nginx
    certbot delete --non-interactive --cert-name "$d" >>/var/log/allskyhub-domains.log 2>&1 || true
    answer "$d" removed
}

shopt -s nullglob
for file in "$SPOOL"/*.remove; do
    teardown "$(basename -- "$file" .remove)"
done
for file in "$SPOOL"/*.request; do
    setup "$(basename -- "$file" .request)"
done
